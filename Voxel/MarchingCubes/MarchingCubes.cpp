// Función auxiliar para obtener el valor de un voxel, considerando chunks vecinos
static float GetVoxelDensity(Chunk& chunk, int x, int y, int z, ChunkManager* chunkManager) {
	// Si las coordenadas están dentro del rango del chunk actual, usa el chunk actual

	// versión 1: 
	if (x > 0 && x < Chunk::CHUNK_SIZE_X - 1 &&
		y > 0 && y < Chunk::CHUNK_SIZE_Y - 1 &&
		z > 0 && z < Chunk::CHUNK_SIZE_Z - 1) {
		return chunk.GetVoxel(x, y, z) ? 1.0f : 0.0f;
	}
	// versión 2:
	/*if (x >= 0 && x < Chunk::CHUNK_SIZE_X &&
		y >= 0 && y < Chunk::CHUNK_SIZE_Y &&
		z >= 0 && z < Chunk::CHUNK_SIZE_Z ) {
		return chunk.GetVoxel(x, y, z) ? 1.0f : 0.0f;
	}*/

	// Si las coordenadas están fuera del rango, busca en el chunk vecino
	int dx = 0, dy = 0, dz = 0;

	// Determinar la dirección del chunk vecino
	if (x == 0) dx = -1;
	if (x >= Chunk::CHUNK_SIZE_X-1) dx = 1;
	if (y == 0) dy = -1;
	if (y >= Chunk::CHUNK_SIZE_Y-1) dy = 1;
	if (z == 0) dz = -1;
	if (z >= Chunk::CHUNK_SIZE_Z-1) dz = 1;

	// Obtener el chunk vecino
	XMFLOAT3 chunkPosition = chunk.GetPosition();
	Chunk* neighborChunk = chunkManager->GetNeighborChunk(
		static_cast<int>(chunkPosition.x),
		static_cast<int>(chunkPosition.y),
		static_cast<int>(chunkPosition.z),
		dx, dy, dz);

	// Si no hay chunk vecino, devuelve 0.0f (aire)
	if (!neighborChunk) {
		return 0.0f;
	}

	// Calcular las coordenadas locales dentro del chunk vecino
	/*int neighborX = (x + Chunk::CHUNK_SIZE_X) % Chunk::CHUNK_SIZE_X;
	int neighborY = (y + Chunk::CHUNK_SIZE_Y) % Chunk::CHUNK_SIZE_Y;
	int neighborZ = (z + Chunk::CHUNK_SIZE_Z) % Chunk::CHUNK_SIZE_Z;*/

	int neighborX = (dx == 1 ) ? 0 : x;
	int neighborY = (dy == 1 ) ? 0 : y;
	int neighborZ = (dz == 1 ) ? 0 : z;

	if (dx == -1) {
		neighborX = Chunk::CHUNK_SIZE_X - 1;
	}
	if (dy == -1) {
		neighborY = Chunk::CHUNK_SIZE_Y - 1;
	}
	if (dz == -1) {
		neighborZ = Chunk::CHUNK_SIZE_Z - 1;
	}

	/*if (dx == -1 || dy == -1 || dx == -1) {
		dx = dx;
	}*/
	
	// Asegurarse de que las coordenadas locales son válidas
	if (!neighborChunk->IsValidVoxelCoordinate(neighborX, neighborY, neighborZ)) {
		return 0.0f;
	}

	// Obtener el valor del voxel en el chunk vecino
	return neighborChunk->GetVoxel(neighborX, neighborY, neighborZ) ? 1.0f : 0.0f;
}

